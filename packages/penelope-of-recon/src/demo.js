import { fileURLToPath } from 'node:url';
import { demoRuntime, printStep } from 'mythos-agent-core';

export async function demo(manifest) {
  const rt = demoRuntime(manifest, fileURLToPath(new URL('../fixtures', import.meta.url)), { mode: 'auto', autoActions: ['penelope_accept_match'] });
  process.stdout.write(`Penelope of Recon demo (fictional bank and GL) in ${rt.root} — Auto on for penelope_accept_match only\n`);
  const st = await rt.call('penelope_read_statement', { bank: 'bank-statement.camt053.xml' });
  printStep('Read a CAMT.053 statement (BAI2 and OFX work the same way)', st);
  const f = { bank: 'bank-statement.csv', gl: 'gl-cash.csv', bank_balance: 12422.88, gl_balance: 12844.76 };
  const r = await rt.call('penelope_reconcile', f);
  printStep('Propose matches and tie balances', r);
  for (const m of r.result.matches) process.stdout.write(`    ${m.confidence.padEnd(6)} ${m.type.padEnd(12)} ${m.bank.join('+')} ↔ ${m.gl.join('+').padEnd(10)} ${m.amount}  ${m.note}\n`);
  for (const b of r.result.bank_only) process.stdout.write(`    bank only  ${b.id} ${b.description} ${b.amount}: ${b.kind}\n`);
  for (const g of r.result.gl_only) process.stdout.write(`    GL only    ${g.id} ${g.description} ${g.amount}: ${g.kind}\n`);
  printStep('Same reconciliation straight from the CAMT.053 file (closing balance read from the file)', await rt.call('penelope_reconcile', { bank: 'bank-statement.camt053.xml', gl: 'gl-cash.csv', gl_balance: 12844.76 }));
  const wp = await rt.call('penelope_write_workpaper', f);
  printStep('Write the workpaper (CSV, Markdown, HTML with sign-off lines)', wp);
  process.stdout.write(`    output_sha256 ${wp.result.output_sha256}\n`);
  printStep('Auto: accept a high-confidence match (opted in)', await rt.call('penelope_accept_match', { bank_ids: r.result.matches[0].bank.join(' '), gl_ids: r.result.matches[0].gl.join(' ') }));
  printStep('Auto: accept the ACH match (opted in)', await rt.call('penelope_accept_match', { bank_ids: 'B4', gl_ids: 'G4', note: 'ACH Acme' }));
  const sug = await rt.call('penelope_suggest_rules', { bank: 'bank-statement.csv', gl: 'gl-cash.csv' });
  printStep('Suggest match rules from accepted matches', sug);
  for (const s of sug.result.suggestions) process.stdout.write(`    ${s.id}: ${s.plain}\n`);
  const s0 = sug.result.suggestions[0];
  const rule = { bank_pattern: s0.bank_pattern, gl_pattern: s0.gl_pattern, direction: s0.direction, max_days: s0.max_days, support: s0.support };
  const ra = await rt.call('penelope_accept_rule', rule);
  printStep('Accept the rule — needs a person (not opted in to Auto)', ra);
  rt.approvals.approve(ra.approval_id, 'Dana Reviewer (fictional)');
  process.stdout.write(`    (demo: "Dana Reviewer" approves ${ra.approval_id})\n`);
  printStep('Same request after the human yes', await rt.call('penelope_accept_rule', rule));
  const rf = await rt.call('penelope_roll_forward', { prior: 'reconciliation-2026-10.csv', bank: 'bank-2026-11.csv', gl: 'gl-cash-2026-11.csv', bank_balance: 16047.88, gl_balance: 15452.88, as_of: '2026-11-30' });
  printStep('November roll-forward from the October workpaper', rf);
  for (const c of rf.result.cleared) process.stdout.write(`    cleared    ${c.prior_item} ${c.description} ${c.amount} by ${c.cleared_by} on ${c.cleared_on}\n`);
  for (const c of rf.result.closing_outstanding) process.stdout.write(`    open       ${c.id} ${c.description} ${c.amount} (${c.origin}, ${c.age_days} day(s))\n`);
  const req = { date: '2026-10-31', amount: -25, account: 'Bank fees expense', memo: 'Monthly service fee Oct 2026', bank_line: 'B7' };
  const a = await rt.call('penelope_request_adjusting_entry', req);
  printStep('Auto: request an adjusting entry — stays one-click', a);
  rt.approvals.approve(a.approval_id, 'Dana Reviewer (fictional)');
  process.stdout.write(`    (demo: "Dana Reviewer" approves ${a.approval_id})\n`);
  printStep('Same request after the human click', await rt.call('penelope_request_adjusting_entry', req));
  printStep('Agent tries to post to the ledger', await rt.call('ledger_post_journal', {}));
  process.stdout.write(`\nAudit log: ${rt.stateDir}/audit.jsonl\n`);
}
