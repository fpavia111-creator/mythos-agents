import { htmlPage, escapeHtml } from 'mythos-agent-core';

const fmt = (n) => (n === null || n === undefined ? '—' : Math.round(n).toLocaleString('en-US'));
const pctS = (p) => (p === null ? '—' : `${p > 0 ? '+' : p < 0 ? '−' : ''}${Math.abs(p).toFixed(1)}%`);

/** Inline Markdown subset: **bold**, `code`; everything else escaped. */
const inline = (s) => escapeHtml(s).replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>').replace(/`([^`]+)`/g, '<code>$1</code>');

/** A small, safe Markdown subset: headings, bullet lists, blockquotes, paragraphs. */
export function mdToHtml(md) {
  const out = []; let list = false;
  const close = () => { if (list) { out.push('</ul>'); list = false; } };
  for (const raw of String(md).split(/\r?\n/)) {
    const line = raw.trimEnd();
    if (!line.trim()) { close(); continue; }
    let m;
    if ((m = /^(#{1,4})\s+(.*)$/.exec(line))) { close(); const lv = Math.min(6, m[1].length + 2); out.push(`<h${lv}>${inline(m[2])}</h${lv}>`); }
    else if ((m = /^\s*[-*]\s+(.*)$/.exec(line))) { if (!list) { out.push('<ul>'); list = true; } out.push(`<li>${inline(m[1])}</li>`); }
    else if ((m = /^>\s?(.*)$/.exec(line))) { close(); out.push(`<blockquote>${inline(m[1])}</blockquote>`); }
    else { close(); out.push(`<p>${inline(line)}</p>`); }
  }
  close();
  return out.join('\n');
}

/** Self-contained HTML rendering of the board pack (no scripts; CSP default-src 'none'). */
export function packHtml({ title, period, figures, lockedSha, vs, docs, claims, charts }) {
  const B = [];
  B.push(`<h1>${escapeHtml(title)}${period ? ` — ${escapeHtml(period)}` : ''}</h1>`);
  B.push('<p class="warn"><strong>DRAFT — not for distribution until a controller signs.</strong></p>');
  B.push(`<p class="mut">Figures: <code>${escapeHtml(figures)}</code> (locked, sha256 ${escapeHtml(lockedSha.slice(0, 12))}…). Claims check: ${claims.ok}/${claims.claims_checked} ok, ${claims.issues} issue(s).</p>`);
  B.push('<h2>Variances</h2><table><thead><tr><th>Id</th><th>Metric</th><th>Actual</th><th>Budget</th><th>vs budget</th><th>Prior</th><th>vs prior</th><th>Material</th></tr></thead><tbody>');
  for (const v of vs) B.push(`<tr><td>${escapeHtml(v.id)}</td><td>${escapeHtml(v.metric)}</td><td class="num">${fmt(v.actual)}</td><td class="num">${fmt(v.budget)}</td><td class="num">${v.var_budget === null ? '—' : `${fmt(v.var_budget)} (${pctS(v.var_budget_pct)})`}</td><td class="num">${fmt(v.prior)}</td><td class="num">${v.var_prior === null ? '—' : `${fmt(v.var_prior)} (${pctS(v.var_prior_pct)})`}</td><td>${v.material ? 'yes' : ''}</td></tr>`);
  B.push('</tbody></table>');
  if (charts.length) {
    B.push('<h2>Charts</h2><p class="mut">Drawn only from the locked figures. Each bar names its figure id.</p>');
    for (const c of charts) B.push(`<figure>${c.svg}</figure>`);
  }
  for (const d of docs) B.push(`<h2>${escapeHtml(d.path)}</h2><p class="mut">Source: <code>${escapeHtml(d.path)}</code> · sha256 ${escapeHtml(d.sha256.slice(0, 12))}…</p>`, mdToHtml(d.text.replace(/^#\s+.*\n?/, '')));
  B.push('<h2>Figure sources</h2><ul>', ...vs.map((v) => `<li>[${escapeHtml(v.id)}] ${escapeHtml(v.metric)}: ${escapeHtml(v.source || '(no source given)')}</li>`), '</ul>');
  B.push('<h2>Claims check</h2>');
  const bad = claims.claims.filter((x) => x.status !== 'ok');
  if (!bad.length) B.push('<p class="ok">Every sentence with a number cites a figure and matches it.</p>');
  else B.push('<ul>', ...bad.map((x) => `<li><strong class="bad">${escapeHtml(x.status)}</strong> — ${escapeHtml(x.doc)}:${x.line}: “${escapeHtml(x.text)}”</li>`), '</ul>');
  return htmlPage({ title: `${title}${period ? ` — ${period}` : ''}`, bodyHtml: B.join('\n'), footer: 'Generated by urania-of-flux from locked figures. DRAFT until signed.' });
}
